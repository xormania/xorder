class AttributionTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.git("init", "--quiet", "--initial-branch=master")
        self.git("config", "user.name", "Fixture Human")
        self.git("config", "user.email", "human@example.test")
        self.base = self.commit("Trusted base")

    def git(self, *arguments, env=None, input=None):
        return subprocess.run(
            ["git", *arguments],
            cwd=self.root,
            env=env,
            input=input,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()

    def commit(
        self,
        message,
        *,
        author_name="Fixture Human",
        author_email="human@example.test",
        committer_name="Fixture Human",
        committer_email="human@example.test",
    ):
        environment = {
            **os.environ,
            "GIT_AUTHOR_NAME": author_name,
            "GIT_AUTHOR_EMAIL": author_email,
            "GIT_COMMITTER_NAME": committer_name,
            "GIT_COMMITTER_EMAIL": committer_email,
        }
        self.git("commit", "--quiet", "--allow-empty", "--file", "-", env=environment, input=message)
        return self.git("rev-parse", "HEAD")

    def inspect(self, base=None, head="HEAD"):
        return attribution.inspect_range(self.root, base or self.base, head)

    def audit(self, head="HEAD"):
        return attribution.inspect_history(self.root, head)

    @staticmethod
    def github_commit(
        sha,
        parents=(),
        *,
        message="Remote change",
        author_name="Fixture Human",
        author_email="human@example.test",
        committer_name="Fixture Human",
        committer_email="human@example.test",
    ):
        return {
            "sha": sha,
            "author": {"name": author_name, "email": author_email},
            "committer": {"name": committer_name, "email": committer_email},
            "message": message,
            "parents": [{"sha": parent} for parent in parents],
            # These untrusted fields are deliberately irrelevant to the audit.
            "tree": {"sha": "f" * 40, "url": "https://example.test/untrusted"},
            "url": "https://example.test/untrusted",
        }

