    def test_github_history_traverses_both_merge_parents_as_metadata(self):
        head = "a" * 40
        left = "b" * 40
        right = "c" * 40
        responses = {
            head: self.github_commit(head, (left, right)),
            left: self.github_commit(
                left,
                (self.base,),
                committer_name="Codex",
            ),
            right: self.github_commit(
                right,
                (self.base,),
                message="Remote change\n\nGenerated by Claude Code",
                author_name="Claude",
            ),
        }

        def fetch(repository, sha, api_url, token):
            self.assertEqual(repository, "base-owner/xorder")
            self.assertEqual(api_url, "https://api.github.test/api/v3")
            self.assertEqual(token, "fixture-token")
            return responses[sha]

        with mock.patch.object(attribution, "_fetch_github_commit", side_effect=fetch) as fetched:
            findings, count = attribution.inspect_github_history(
                self.root,
                "HEAD",
                head,
                "base-owner/xorder",
                "https://api.github.test/api/v3/",
                "fixture-token",
            )
        self.assertEqual(count, 4)
        self.assertEqual({call.args[1] for call in fetched.call_args_list}, {head, left, right})
        self.assertNotIn(self.base, {call.args[1] for call in fetched.call_args_list})
        self.assertCountEqual(
            [finding.kind for finding in findings],
            ["author identity", "committer identity", "AI generation signature"],
        )

