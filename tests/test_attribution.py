    def test_github_commit_request_keeps_token_on_fixed_api_url(self):
        proposed = "d" * 40
        url = (
            "https://api.github.test/api/v3/repos/base-owner/xorder/"
            f"git/commits/{proposed}"
        )
        response = mock.MagicMock()
        response.__enter__.return_value = response
        response.geturl.return_value = url
        response.read.return_value = json.dumps(self.github_commit(proposed)).encode()
        opener = mock.MagicMock()
        opener.open.return_value = response
        with mock.patch.object(
            attribution.urllib.request,
            "build_opener",
            return_value=opener,
        ) as build_opener:
            payload = attribution._fetch_github_commit(
                "base-owner/xorder",
                proposed,
                "https://api.github.test/api/v3",
                "fixture-token",
            )
        self.assertEqual(payload["sha"], proposed)
        request = opener.open.call_args.args[0]
        self.assertEqual(request.full_url, url)
        self.assertEqual(request.get_header("Authorization"), "Bearer fixture-token")
        redirect_handler = build_opener.call_args.args[0]
        self.assertIsNone(redirect_handler.redirect_request(
            request,
            None,
            302,
            "Found",
            {},
            "https://example.test/untrusted",
        ))

